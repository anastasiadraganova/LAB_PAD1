"""Промпты генерации. Сравниваются в эксперименте «LLM × промпт»."""
from __future__ import annotations

from src.retrieval import Hit

REFUSAL = "В базе знаний недостаточно информации для ответа на этот вопрос."

PROMPTS = {
    # строгий: только контекст, обязательные ссылки, явный отказ
    "strict": f"""Ты — ассистент-эксперт по астрономии и Солнечной системе. Отвечай на вопрос пользователя, опираясь ТОЛЬКО на фрагменты контекста ниже.

Правила:
1. Используй только факты из контекста. Не добавляй знания от себя, даже если уверен в них.
2. После каждого утверждения ставь ссылку на номер фрагмента в квадратных скобках, например [1] или [2][3].
3. Если в контексте нет информации для ответа (или она относится к другому объекту), ответь ровно фразой: «{REFUSAL}» — и больше ничего не пиши.
4. Если информации хватает только на часть вопроса — ответь на эту часть и прямо скажи, чего в базе нет.
5. Числа, даты и названия приводи точно как в контексте.
6. Отвечай на русском языке. Будь краток: 1–5 предложений.""",

    # базовый: «вот контекст, ответь» — без запрета на собственные знания и без ссылок
    "basic": """Ты — полезный ассистент по астрономии. Ниже приведены фрагменты из базы знаний, которые могут помочь ответить на вопрос. Ответь на вопрос пользователя на русском языке.""",
}


def format_context(hits: list[Hit]) -> str:
    blocks = []
    for i, h in enumerate(hits, 1):
        c = h.chunk
        blocks.append(f"[{i}] {c.title} — {c.section} (Википедия)\n{c.text}")
    return "\n\n".join(blocks)


def build_messages(prompt_key: str, question: str, hits: list[Hit]) -> list[dict]:
    context = format_context(hits) if hits else "(контекст пуст)"
    return [
        {"role": "system", "content": PROMPTS[prompt_key]},
        {"role": "user", "content": f"Контекст:\n{context}\n\nВопрос: {question}"},
    ]
